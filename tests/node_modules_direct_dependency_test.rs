use std::fs;
use tempfile::TempDir;

use ai_agent_audit::utils::check_folder_name::is_library_package_json;

#[test]
fn test_node_modules_direct_dependency_detection() {
    // Create a temporary directory structure
    let temp_dir = TempDir::new().unwrap();
    let root = temp_dir.path();

    println!("\n=== Testing node_modules direct dependency detection ===");
    println!("Root: {}\n", root.display());

    // Create root package.json with dependencies
    let root_package_json = root.join("package.json");
    fs::write(
        &root_package_json,
        r#"{
  "name": "test-project",
  "dependencies": {
    "@openzeppelin/contracts": "^4.9.0",
    "hardhat": "^2.17.0"
  },
  "devDependencies": {
    "@nomicfoundation/hardhat-toolbox": "^3.0.0"
  }
}"#,
    )
    .unwrap();

    // Test 1: Direct dependency (regular package)
    let hardhat_pkg = root.join("node_modules/hardhat/package.json");
    fs::create_dir_all(hardhat_pkg.parent().unwrap()).unwrap();
    fs::write(&hardhat_pkg, "{}").unwrap();

    assert!(
        is_library_package_json(&hardhat_pkg, root),
        "Should detect hardhat as direct dependency"
    );
    println!("✅ Test 1 passed: Direct dependency (regular package)");

    // Test 2: Direct dependency (scoped package)
    let oz_pkg = root.join("node_modules/@openzeppelin/contracts/package.json");
    fs::create_dir_all(oz_pkg.parent().unwrap()).unwrap();
    fs::write(&oz_pkg, "{}").unwrap();

    assert!(
        is_library_package_json(&oz_pkg, root),
        "Should detect @openzeppelin/contracts as direct dependency"
    );
    println!("✅ Test 2 passed: Direct dependency (scoped package)");

    // Test 3: Dev dependency (scoped package)
    let toolbox_pkg = root.join("node_modules/@nomicfoundation/hardhat-toolbox/package.json");
    fs::create_dir_all(toolbox_pkg.parent().unwrap()).unwrap();
    fs::write(&toolbox_pkg, "{}").unwrap();

    assert!(
        is_library_package_json(&toolbox_pkg, root),
        "Should detect @nomicfoundation/hardhat-toolbox as dev dependency"
    );
    println!("✅ Test 3 passed: Dev dependency (scoped package)");

    // Test 4: Transitive dependency (NOT in package.json)
    let transitive_pkg = root.join("node_modules/some-transitive-dep/package.json");
    fs::create_dir_all(transitive_pkg.parent().unwrap()).unwrap();
    fs::write(&transitive_pkg, "{}").unwrap();

    assert!(
        !is_library_package_json(&transitive_pkg, root),
        "Should NOT detect transitive dependency (not in package.json)"
    );
    println!("✅ Test 4 passed: Transitive dependency rejected");

    // Test 5: Nested node_modules (should be rejected by path_has_one_segment)
    let nested_pkg = root.join("node_modules/hardhat/node_modules/nested/package.json");
    fs::create_dir_all(nested_pkg.parent().unwrap()).unwrap();
    fs::write(&nested_pkg, "{}").unwrap();

    assert!(
        !is_library_package_json(&nested_pkg, root),
        "Should NOT detect nested node_modules package"
    );
    println!("✅ Test 5 passed: Nested node_modules rejected");

    // Test 6: Scoped package transitive dependency
    let scoped_transitive = root.join("node_modules/@some-scope/transitive/package.json");
    fs::create_dir_all(scoped_transitive.parent().unwrap()).unwrap();
    fs::write(&scoped_transitive, "{}").unwrap();

    assert!(
        !is_library_package_json(&scoped_transitive, root),
        "Should NOT detect scoped transitive dependency"
    );
    println!("✅ Test 6 passed: Scoped transitive dependency rejected");

    // Test 7: node_modules with lib subfolder (e.g., ethers/lib.commonjs)
    // Add ethers to package.json first
    fs::write(
        &root_package_json,
        r#"{
  "name": "test-project",
  "dependencies": {
    "@openzeppelin/contracts": "^4.9.0",
    "hardhat": "^2.17.0",
    "ethers": "^6.0.0"
  },
  "devDependencies": {
    "@nomicfoundation/hardhat-toolbox": "^3.0.0"
  }
}"#,
    )
    .unwrap();

    let ethers_lib = root.join("node_modules/ethers/lib/package.json");
    fs::create_dir_all(ethers_lib.parent().unwrap()).unwrap();
    fs::write(&ethers_lib, "{}").unwrap();

    assert!(
        !is_library_package_json(&ethers_lib, root),
        "Should NOT detect package.json in node_modules/ethers/lib/ (contains 'lib' segment)"
    );
    println!("✅ Test 7 passed: node_modules with lib subfolder rejected");

    // Test 8: Double nested node_modules with lib
    let double_nested = root.join("node_modules/pkg/node_modules/nested/lib/package.json");
    fs::create_dir_all(double_nested.parent().unwrap()).unwrap();
    fs::write(&double_nested, "{}").unwrap();

    assert!(
        !is_library_package_json(&double_nested, root),
        "Should NOT detect double nested node_modules with lib"
    );
    println!("✅ Test 8 passed: Double nested node_modules with lib rejected");

    println!("\n✅ All node_modules direct dependency tests passed!");
}

#[test]
fn test_extract_package_name_from_path() {
    use std::path::PathBuf;

    println!("\n=== Testing package name extraction ===\n");

    // Test regular package
    let path1 = PathBuf::from("node_modules/lodash/package.json");
    let name1 =
        ai_agent_audit::utils::check_folder_name::extract_package_name_from_node_modules(&path1);
    assert_eq!(name1, Some("lodash".to_string()));
    println!("✅ Regular package: {:?} -> {:?}", path1, name1);

    // Test scoped package
    let path2 = PathBuf::from("node_modules/@openzeppelin/contracts/package.json");
    let name2 =
        ai_agent_audit::utils::check_folder_name::extract_package_name_from_node_modules(&path2);
    assert_eq!(name2, Some("@openzeppelin/contracts".to_string()));
    println!("✅ Scoped package: {:?} -> {:?}", path2, name2);

    // Test nested (should still extract first occurrence)
    let path3 = PathBuf::from("node_modules/pkg/node_modules/nested/package.json");
    let name3 =
        ai_agent_audit::utils::check_folder_name::extract_package_name_from_node_modules(&path3);
    assert_eq!(name3, Some("pkg".to_string()));
    println!("✅ Nested package: {:?} -> {:?}", path3, name3);

    // Test with full path
    let path4 = PathBuf::from("/home/user/project/node_modules/@scope/package/lib/index.js");
    let name4 =
        ai_agent_audit::utils::check_folder_name::extract_package_name_from_node_modules(&path4);
    assert_eq!(name4, Some("@scope/package".to_string()));
    println!("✅ Full path: {:?} -> {:?}", path4, name4);

    println!("\n✅ All package name extraction tests passed!");
}

#[test]
fn test_megapot_real_world_cases() {
    // Test real-world cases from the megapot project output
    let temp_dir = TempDir::new().unwrap();
    let root = temp_dir.path();

    println!("\n=== Testing real-world megapot cases ===");
    println!("Root: {}\n", root.display());

    // Create root package.json with actual megapot dependencies
    let root_package_json = root.join("package.json");
    fs::write(
        &root_package_json,
        r#"{
  "name": "megapot",
  "dependencies": {
    "@openzeppelin/contracts": "^5.0.0",
    "solady": "^0.0.228",
    "ethers": "^6.7.1",
    "hardhat": "^2.17.2"
  },
  "devDependencies": {
    "@nomicfoundation/hardhat-toolbox": "^3.0.0"
  }
}"#,
    )
    .unwrap();

    // Test 1: Should ACCEPT - Direct dependency
    let oz_pkg = root.join("node_modules/@openzeppelin/contracts/package.json");
    fs::create_dir_all(oz_pkg.parent().unwrap()).unwrap();
    fs::write(&oz_pkg, "{}").unwrap();
    assert!(
        is_library_package_json(&oz_pkg, root),
        "✅ Should accept: node_modules/@openzeppelin/contracts/package.json"
    );
    println!("✅ ACCEPT: node_modules/@openzeppelin/contracts/package.json");

    // Test 2: Should ACCEPT - ethers/lib.commonjs (lib.commonjs != lib, it's just a folder name)
    let ethers_lib_commonjs = root.join("node_modules/ethers/lib.commonjs/package.json");
    fs::create_dir_all(ethers_lib_commonjs.parent().unwrap()).unwrap();
    fs::write(&ethers_lib_commonjs, "{}").unwrap();
    assert!(
        is_library_package_json(&ethers_lib_commonjs, root),
        "✅ Should accept: node_modules/ethers/lib.commonjs/package.json (lib.commonjs is not 'lib')"
    );
    println!("✅ ACCEPT: node_modules/ethers/lib.commonjs/package.json (lib.commonjs != lib)");

    // Test 3: Should ACCEPT - ethers/lib.esm (lib.esm != lib, it's just a folder name)
    let ethers_lib_esm = root.join("node_modules/ethers/lib.esm/package.json");
    fs::create_dir_all(ethers_lib_esm.parent().unwrap()).unwrap();
    fs::write(&ethers_lib_esm, "{}").unwrap();
    assert!(
        is_library_package_json(&ethers_lib_esm, root),
        "✅ Should accept: node_modules/ethers/lib.esm/package.json (lib.esm is not 'lib')"
    );
    println!("✅ ACCEPT: node_modules/ethers/lib.esm/package.json (lib.esm != lib)");

    // Test 4: Should REJECT - Nested node_modules with lib
    let nested_lib =
        root.join("node_modules/@scure/bip32/node_modules/@scure/base/lib/esm/package.json");
    fs::create_dir_all(nested_lib.parent().unwrap()).unwrap();
    fs::write(&nested_lib, "{}").unwrap();
    assert!(
        !is_library_package_json(&nested_lib, root),
        "❌ Should reject: nested node_modules with lib"
    );
    println!(
        "✅ REJECT: node_modules/@scure/bip32/node_modules/@scure/base/lib/esm/package.json (nested + lib)"
    );

    // Test 5: Should REJECT - Nested node_modules (transitive dependency)
    let nested_nm =
        root.join("node_modules/hardhat/node_modules/@scure/bip32/lib/esm/package.json");
    fs::create_dir_all(nested_nm.parent().unwrap()).unwrap();
    fs::write(&nested_nm, "{}").unwrap();
    assert!(
        !is_library_package_json(&nested_nm, root),
        "❌ Should reject: nested node_modules"
    );
    println!(
        "✅ REJECT: node_modules/hardhat/node_modules/@scure/bip32/lib/esm/package.json (nested + lib)"
    );

    // Test 6: Should ACCEPT - Direct dependency (ethers root package.json)
    let ethers_root = root.join("node_modules/ethers/package.json");
    fs::create_dir_all(ethers_root.parent().unwrap()).unwrap();
    fs::write(&ethers_root, "{}").unwrap();
    assert!(
        is_library_package_json(&ethers_root, root),
        "✅ Should accept: node_modules/ethers/package.json"
    );
    println!("✅ ACCEPT: node_modules/ethers/package.json");

    // Test 7: Should REJECT - Actual lib folder (not lib.commonjs)
    let ethers_actual_lib = root.join("node_modules/ethers/lib/package.json");
    fs::create_dir_all(ethers_actual_lib.parent().unwrap()).unwrap();
    fs::write(&ethers_actual_lib, "{}").unwrap();
    assert!(
        !is_library_package_json(&ethers_actual_lib, root),
        "❌ Should reject: node_modules/ethers/lib/package.json (contains actual 'lib' folder)"
    );
    println!("✅ REJECT: node_modules/ethers/lib/package.json (contains actual 'lib' folder)");

    // Test 8: Should REJECT - Multiple lib folders
    let multi_lib = root.join("node_modules/ethers/lib/library/package.json");
    fs::create_dir_all(multi_lib.parent().unwrap()).unwrap();
    fs::write(&multi_lib, "{}").unwrap();
    assert!(
        !is_library_package_json(&multi_lib, root),
        "❌ Should reject: node_modules/ethers/lib/library/package.json (multiple lib folders)"
    );
    println!("✅ REJECT: node_modules/ethers/lib/library/package.json (multiple lib folders)");

    println!("\n✅ All real-world megapot tests passed!");
}

#[test]
fn test_foundry_lib_folder_behavior() {
    // Test Foundry project lib folder behavior
    let temp_dir = TempDir::new().unwrap();
    let root = temp_dir.path();

    println!("\n=== Testing Foundry lib folder behavior ===");
    println!("Root: {}\n", root.display());

    // Foundry projects don't have package.json, so no node_modules check

    // Test 1: Should ACCEPT - Single lib folder
    let single_lib = root.join("lib/openzeppelin-contracts/package.json");
    fs::create_dir_all(single_lib.parent().unwrap()).unwrap();
    fs::write(&single_lib, "{}").unwrap();
    assert!(
        is_library_package_json(&single_lib, root),
        "✅ Should accept: lib/openzeppelin-contracts/package.json"
    );
    println!("✅ ACCEPT: lib/openzeppelin-contracts/package.json");

    // Test 2: Should REJECT - Nested lib folders (lib/foo/lib/bar)
    let nested_lib = root.join("lib/openzeppelin-contracts/lib/utils/package.json");
    fs::create_dir_all(nested_lib.parent().unwrap()).unwrap();
    fs::write(&nested_lib, "{}").unwrap();
    assert!(
        !is_library_package_json(&nested_lib, root),
        "❌ Should reject: lib/openzeppelin-contracts/lib/utils/package.json (nested lib)"
    );
    println!("✅ REJECT: lib/openzeppelin-contracts/lib/utils/package.json (nested lib)");

    // Test 3: Should REJECT - lib + library folders
    let lib_library = root.join("lib/foo/library/package.json");
    fs::create_dir_all(lib_library.parent().unwrap()).unwrap();
    fs::write(&lib_library, "{}").unwrap();
    assert!(
        !is_library_package_json(&lib_library, root),
        "❌ Should reject: lib/foo/library/package.json (lib + library)"
    );
    println!("✅ REJECT: lib/foo/library/package.json (lib + library)");

    // Test 4: Should ACCEPT - Single library folder
    let single_library = root.join("library/contracts/package.json");
    fs::create_dir_all(single_library.parent().unwrap()).unwrap();
    fs::write(&single_library, "{}").unwrap();
    assert!(
        is_library_package_json(&single_library, root),
        "✅ Should accept: library/contracts/package.json"
    );
    println!("✅ ACCEPT: library/contracts/package.json");

    println!("\n✅ All Foundry lib folder tests passed!");
}
